export function calculateMedicineStatus(current: number, minSafe: number, capacity: number): MedicineStatus {
  if (current <= minSafe * 0.5) return 'critical_shortage';
  if (current <= minSafe) return 'low_stock';
  if (current >= capacity * 0.75) return 'surplus';
  return 'adequate';
}

/**
 * Unified background transferability calculation:
 * Total Available - Current Requirement - Emergency Reserve = Safe Transferable Quantity
 */
export function calculateTransferability(
  available: number,
  requirement: number,
  reserve: number,
  requested: number = 1
): TransferabilityAssessment {
  const safeTransferable = Math.max(0, available - requirement - reserve);
  let status: 'can_transfer' | 'limited_transfer' | 'cannot_transfer' = 'cannot_transfer';
  let reason = '';

  if (safeTransferable >= requested && safeTransferable > 0) {
    status = 'can_transfer';
    reason = `🟢 Can Transfer ${requested}: Within Safe Reserve. Safe transferable capacity is ${safeTransferable} while preserving mandatory local emergency reserve (${reserve}).`;
  } else if (safeTransferable > 0 && safeTransferable < requested) {
    status = 'limited_transfer';
    reason = `🟡 Limited Transfer: Maximum safely transferable is ${safeTransferable} (Requested: ${requested}). Local reserve (${reserve}) must not be breached.`;
  } else {
    status = 'cannot_transfer';
    reason = `🔴 Cannot Transfer: Available stock (${available}) is at or below local requirement (${requirement}) plus emergency reserve (${reserve}).`;
  }

  return {
    available,
    requirement,
    reserve,
    safeTransferable,
    status,
    reason,
  };
}

